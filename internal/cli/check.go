package cli

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/spf13/cobra"

	"github.com/exarth-labs/stuntdb/internal/app"
)

func newCheckCmd(opts *globalOptions) *cobra.Command {
	var update bool
	cmd := &cobra.Command{
		Use:   "check",
		Short: "Check the masking rules against the database and stuntdb.lock",
		Long: "check reads the source database's structure (never its rows) and decides how\n" +
			"every column is masked: by its rule in stuntdb.yaml, by a safe classification,\n" +
			"or as a foreign key masked like the column it references. It fails, with exit\n" +
			"code 3, when a column has no decision, a rule is not allowed, or anything\n" +
			"differs from stuntdb.lock. Run it in CI.\n\n" +
			"With --update, it writes stuntdb.lock from the current decisions instead.\n" +
			"Review the change, and commit it.",
		Args: cobra.NoArgs,
		RunE: runE(func(cmd *cobra.Command, _ []string) error {
			res, err := app.Check(cmd.Context(), app.CheckRequest{Env: opts.env, ConfigPath: opts.config, Update: update})
			if res != nil {
				// A failed check still has a result: what it found.
				text := func(r *app.CheckResult) string { return checkText(r, update) }
				if werr := render(cmd.OutOrStdout(), opts.json, res, text); werr != nil {
					return werr
				}
			}
			return err
		}),
	}
	cmd.Flags().BoolVar(&update, "update", false, "write stuntdb.lock from the current decisions, instead of comparing with it")
	return cmd
}

func checkText(r *app.CheckResult, update bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Checked %s in %s:\n", plural(r.Columns, "column"), plural(r.Tables, "table"))
	d := r.Decisions
	writeCounts(&b, r.Columns, []count{
		{d.Configured, "decided by a rule in " + r.Config},
		{d.Safe, "kept as safe"},
		{d.References, "masked like the columns they reference"},
		{d.Policy, "decided by masking.unclassified"},
		{d.Generated, "generated by the database"},
		{d.Unreviewed, "without a decision"},
		{d.Waiting, "waiting for the columns they reference to be decided"},
	})
	if len(r.Problems) > 0 {
		fmt.Fprintf(&b, "\n%s:\n", plural(len(r.Problems), "problem"))
		for _, p := range r.Problems {
			fmt.Fprintf(&b, "  %s\n", p)
		}
	}
	switch {
	case r.LockfileWritten:
		fmt.Fprintf(&b, "\nWrote %s. Review the change, and commit it.\n", r.Lockfile)
	case update:
		fmt.Fprintf(&b, "\n%s was not written: fix the mistakes above first.\n", r.Lockfile)
	}
	return b.String()
}

// count is one line of a summary: how many columns, and what about them.
type count struct {
	n    int
	what string
}

// writeCounts writes the lines with a count above zero, with the counts
// lined up as wide as total.
func writeCounts(b *strings.Builder, total int, counts []count) {
	width := len(strconv.Itoa(total))
	for _, c := range counts {
		if c.n > 0 {
			fmt.Fprintf(b, "  %*d %s\n", width, c.n, c.what)
		}
	}
}
