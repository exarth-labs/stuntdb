// LockPath is the lockfile, next to the project configuration.
const LockPath = "stuntdb.lock"

// Unreviewed is the decision of a column that no one has reviewed yet. Any
// such column makes the check fail.
const Unreviewed = "UNREVIEWED"

// Generated is the decision of a generated column. Its values are never
// copied: the target computes them again, from the masked columns.
const Generated = "generated"

const lockVersion = 1

const lockHeader = `stuntdb.lock: generated by "stuntdb check --update". Do not edit it by hand;
review its changes in pull requests.`

// ErrNoLock is returned when the lockfile does not exist.
var ErrNoLock = errors.New("config: no lockfile")

// Lock is the lockfile. It records the decision for every column, including
// the implicit ones, and a fingerprint of the schema, so that every change
// shows up as a diff in review.
type Lock struct {
	GeneratedBy       string // the stuntdb version that wrote it
	GeneratorVersion  int    // the version of the fake-value generators, which decides the masked values
	SchemaFingerprint string
	Tables            []*LockTable
}

// LockTable holds the decisions for one table's columns.
type LockTable struct {
	Table   TableName
	Columns []*LockColumn
}

// LockColumn is the decision for one column. Everything that decides the
// fake values is recorded, so that a change to any of it is a diff.
type LockColumn struct {
	Column   string
	Decision string            // keep, null, a transformer name, Generated or Unreviewed
	Source   string            // why: "config", "rule core.email", …; empty for Generated and Unreviewed
	Options  map[string]string // the transformer's options, as text (OptionText)
	Domain   string            // the domain, when it isn't the column's own default
	Per      string            // the column that seeds this one, if any
	At       Position          // where it is in the file, when read
}

// SameRule reports whether two decisions mask a column the same way: the
// same decision, source, options, domain and seed column.
func (c *LockColumn) SameRule(o *LockColumn) bool {
	return c.Decision == o.Decision && c.Source == o.Source && maps.Equal(c.Options, o.Options) && c.Domain == o.Domain && c.Per == o.Per
}

// Column returns the decision for a column, or nil.
func (l *Lock) Column(table TableName, column string) *LockColumn {
	for _, t := range l.Tables {
		if t.Table != table {
			continue
		}
		for _, c := range t.Columns {
			if c.Column == column {
				return c
			}
		}
	}
	return nil
}

// Marshal returns the lockfile's text. Tables and columns are sorted, so that
// the same decisions always give the same file.
func (l *Lock) Marshal() ([]byte, error) {
	tables := slices.Clone(l.Tables)
	slices.SortFunc(tables, func(a, b *LockTable) int { return cmp.Compare(a.Table.String(), b.Table.String()) })

	columns := mapping()
	for _, t := range tables {
		cols := slices.Clone(t.Columns)
		slices.SortFunc(cols, func(a, b *LockColumn) int { return cmp.Compare(a.Column, b.Column) })
		rules := mapping()
		for _, c := range cols {
			decision := mapping()
			decision.Style = yaml.FlowStyle
			add(decision, "decision", text(c.Decision))
			if c.Source != "" {
				add(decision, "source", text(c.Source))
			}
			if len(c.Options) > 0 {
				options := mapping()
				options.Style = yaml.FlowStyle
				for _, k := range slices.Sorted(maps.Keys(c.Options)) {
					add(options, k, text(c.Options[k]))
				}
				add(decision, "options", options)
			}
			if c.Domain != "" {
				add(decision, "domain", text(c.Domain))
			}
			if c.Per != "" {
				add(decision, "per", text(c.Per))
			}
			add(rules, c.Column, decision)
		}
		add(columns, t.Table.String(), rules)
	}

	root := mapping()
	root.HeadComment = lockHeader
	add(root, "lock_version", number(lockVersion))
	add(root, "generated_by", text(l.GeneratedBy))
	add(root, "generator_version", number(l.GeneratorVersion))
	add(root, "schema_fingerprint", text(l.SchemaFingerprint))
	add(root, "columns", columns)

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, fmt.Errorf("config: write the lockfile: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("config: write the lockfile: %w", err)
	}
	return buf.Bytes(), nil
}

func mapping() *yaml.Node { return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"} }

// text is a string. The encoder writes << without quotes, which YAML then
// reads as its merge key, so it is always quoted.
func text(s string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s}
	if s == "<<" {
		n.Style = yaml.DoubleQuotedStyle
	}
	return n
}

func number(n int) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.Itoa(n)}
}

func add(m *yaml.Node, key string, v *yaml.Node) { m.Content = append(m.Content, text(key), v) }

// Write saves the lockfile atomically: a crash never leaves half a file.
func (l *Lock) Write(ctx context.Context, path string) error {
	data, err := l.Marshal()
	if err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".partial-*")
	if err != nil {
		return errs.E(errs.Output, fmt.Errorf("config: write the lockfile: %w", pathless(err)))
	}
	_, werr := tmp.Write(data)
	cerr := tmp.Close()
	if err := errors.Join(werr, cerr); err != nil {
		_ = os.Remove(tmp.Name())
		return errs.E(errs.Output, fmt.Errorf("config: write the lockfile: %w", pathless(err)))
	}
	if err := outfile.Commit(ctx, tmp.Name(), path); err != nil {
		_ = os.Remove(tmp.Name())
		return errs.E(errs.Output, fmt.Errorf("config: write the lockfile: %w", err))
	}
	return nil
}

// ReadLock reads a lockfile. A missing file is ErrNoLock. Its other errors
// carry errs.Usage.
func ReadLock(path string) (*Lock, error) {
	data, err := os.ReadFile(path) //nolint:gosec // the project's own lockfile
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNoLock
	}
	if err != nil {
		return nil, errs.E(errs.Usage, fmt.Errorf("config: cannot read %s: %w", path, pathless(err)))
	}
	l, err := parseLock(path, data)
	return l, errs.E(errs.Usage, err)
}

func parseLock(path string, data []byte) (*Lock, error) {
	f, err := parseFile(path, data)
	if err != nil {
		return nil, err
	}
	l := &Lock{}
	var ps problems
	version := -1
	for i := 0; i+1 < len(f.root.Content); i += 2 {
		k, v := f.root.Content[i], f.root.Content[i+1]
		switch k.Value {
		case "lock_version":
			version = f.int(v, &ps)
		case "generated_by":
			l.GeneratedBy = f.str(v, &ps)
		case "generator_version":
			l.GeneratorVersion = f.int(v, &ps)
		case "schema_fingerprint":
			l.SchemaFingerprint = f.str(v, &ps)
		case "columns":
			l.Tables = f.lockTables(v, &ps)
		default:
			ps.add(f.pos(k), "unknown lockfile entry %s", strconv.Quote(k.Value))
		}
	}
	switch {
	case version == -1:
		ps.add(f.pos(f.root), "lock_version is missing")
	case version != lockVersion:
		ps.add(f.pos(f.root), "lock_version %d is not supported; this stuntdb reads version %d. Update stuntdb, or run \"stuntdb check --update\"", version, lockVersion)
	}
	return l, ps.err()
}

func (f *file) lockTables(n *yaml.Node, ps *problems) []*LockTable {
	if n.Kind != yaml.MappingNode {
		ps.add(f.pos(n), "columns must be a set of tables")
		return nil
	}
	var tables []*LockTable
	for i := 0; i+1 < len(n.Content); i += 2 {
		k, v := n.Content[i], n.Content[i+1]
		name, err := ParseTableName(k.Value)
		if err != nil {
			ps.add(f.pos(k), "%v", err)
			continue
		}
		t := &LockTable{Table: name}
		if v.Kind != yaml.MappingNode {
			ps.add(f.pos(v), "table %s must be a set of columns", name)
			continue
		}
		for j := 0; j+1 < len(v.Content); j += 2 {
			ck, cv := v.Content[j], v.Content[j+1]
			c := &LockColumn{Column: ck.Value, At: f.pos(ck)}
			if cv.Kind != yaml.MappingNode {
				ps.add(f.pos(cv), "column %s must have a decision", strconv.Quote(ck.Value))
				continue
			}
			for m := 0; m+1 < len(cv.Content); m += 2 {
				switch key := cv.Content[m].Value; key {
				case "decision":
					c.Decision = f.str(cv.Content[m+1], ps)
				case "source":
					c.Source = f.str(cv.Content[m+1], ps)
				case "options":
					c.Options = f.lockOptions(cv.Content[m+1], ps)
				case "domain":
					c.Domain = f.str(cv.Content[m+1], ps)
				case "per":
					c.Per = f.str(cv.Content[m+1], ps)
				default:
					ps.add(f.pos(cv.Content[m]), "unknown entry %s", strconv.Quote(key))
				}
			}
			if c.Decision == "" {
				ps.add(f.pos(ck), "column %s has no decision", strconv.Quote(ck.Value))
			}
			t.Columns = append(t.Columns, c)
		}
		tables = append(tables, t)
	}
	return tables
}

// lockOptions reads a decision's options: a set of names and single values.
func (f *file) lockOptions(n *yaml.Node, ps *problems) map[string]string {
	if n.Kind != yaml.MappingNode {
		ps.add(f.pos(n), "options must be a set of names and values")
		return nil
	}
	out := make(map[string]string, len(n.Content)/2)
	for i := 0; i+1 < len(n.Content); i += 2 {
		out[n.Content[i].Value] = f.str(n.Content[i+1], ps)
	}
	return out
}

func (f *file) str(n *yaml.Node, ps *problems) string {
	if n.Kind != yaml.ScalarNode {
		ps.add(f.pos(n), "must be text")
		return ""
	}
	return n.Value
}

func (f *file) int(n *yaml.Node, ps *problems) int {
	i, err := strconv.Atoi(n.Value)
	if n.Kind != yaml.ScalarNode || err != nil {
		ps.add(f.pos(n), "must be a whole number")
		return 0
	}
	return i
}
